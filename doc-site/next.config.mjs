// Next.js configuration of the cmd_ai documentation site (Fumadocs).
//
// Developer notes (no README here: the constitution forbids any .md/.mdx
// content under doc-site/, the site only *reads* ../doc and ../bug):
//
// - Content: source.config.ts declares two collections that read the
//   repository Markdown in place, `../doc` (rendered under /docs) and `../bug`
//   (rendered under /bugs; bug/README.md is the /bugs index, `_*.md` templates
//   such as bug/_modele.md are excluded). Navigation order of doc/ comes from
//   doc/meta.json (`pages`, with `...` for the rest).
// - Every doc/ page needs `title` and `description` in its frontmatter: the
//   build fails otherwise (they also feed SEO and search).
//   A bug sheet without frontmatter still renders: its title falls back to
//   its first `# heading`, then to its file name.
// - Links between Markdown files are written GitHub-style (`./config.md`,
//   `../bug/README.md#etat`) and resolved at render time (lib/links.ts): a
//   page of doc/ or bug/ becomes its site URL, any other repository file a
//   GitHub link. A leading `# Title` is dropped (the layout prints the title).
// - Commands, from doc-site/: `pnpm install` then `pnpm build`, which writes
//   the static site to doc-site/out/. Never `pnpm dev` here (the owner runs
//   the dev server). `pnpm types:check` runs the TypeScript check alone.
//   `.source/` is generated by fumadocs-mdx at build time (git-ignored).
// - Static export only (GitHub Pages): no rewrites, redirects, headers, proxy
//   or request-dependent route handlers; "/" is a landing page linking to
//   /docs, not a redirect. Search is a static index rendered at build time by
//   app/search-index.json/route.ts (docs + bugs, French tokenizer and
//   stemmer, lib/search.ts) and queried in the browser (components/search.tsx).
//   UI strings are translated in lib/translations.ts (html lang="fr").
// - Known harmless build output: two "'highlight' is not recognized as a
//   valid pseudo-element" CSS warnings come from a fumadocs-ui class
//   (`::highlight(fd-search)`), not from this app.
// - pnpm: esbuild's install script is not needed (its binary ships as an
//   optional dependency), hence `pnpm.ignoredBuiltDependencies`.
// - Environment variables read at build time:
//     PAGES_BASE_PATH                       base path, e.g. `/cmd_ai` on
//                                           <owner>.github.io/cmd_ai (default '')
//     NEXT_PUBLIC_SITE_URL                  public URL, base path included
//                                           (default https://brandonviry.github.io/cmd_ai)
//     NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION  Google Search Console token, emitted
//                                           as <meta name="google-site-verification">
//   PAGES_BASE_PATH and NEXT_PUBLIC_SITE_URL must agree (same path suffix).
// - SEO: canonical URLs, per-page title/description from frontmatter, and
//   /sitemap.xml (submit it by hand in Search Console: robots.txt only counts
//   at the host root, so a project page cannot declare it).
// - Turbopack only resolves files inside its root: since the content lives
//   outside this app, the root is the repository root.
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createMDX } from 'fumadocs-mdx/next';

const appDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.join(appDir, '..');

/** `/cmd_ai`, `cmd_ai/` or '' → `/cmd_ai` or '' (Next requires no trailing slash). */
function normalizeBasePath(value) {
  const trimmed = (value ?? '').trim().replace(/^\/+|\/+$/g, '');
  return trimmed ? `/${trimmed}` : '';
}

const basePath = normalizeBasePath(process.env.PAGES_BASE_PATH);

const withMDX = createMDX();

/** @type {import('next').NextConfig} */
const config = {
  output: 'export',
  trailingSlash: true,
  basePath,
  images: { unoptimized: true },
  reactStrictMode: true,
  env: {
    // Exposed to client code that builds raw URLs (the search index fetch).
    NEXT_PUBLIC_BASE_PATH: basePath,
  },
  turbopack: {
    root: repoRoot,
  },
  outputFileTracingRoot: repoRoot,
};

export default withMDX(config);
